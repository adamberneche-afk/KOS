// FILE: 79_CanvasWeeklyCartridge.js
// BOUND TO: Central Ledger spreadsheet (cas-ccps:central-ledger)
//
// The week's Canvas assignments, with due dates (2026-11-19, the operator:
// lessons were opening before their Canvas assignment was posted; no Canvas
// API token or approval is available, so CAS can't post them itself).
//
//   previewWeeklyCanvasCartridge()  what a cartridge would hold; writes nothing
//   buildWeeklyCanvasCartridge()    one cartridge (.imscc) per course in the
//                                   teacher folder (TEACHER_FOLDER_ID, else My
//                                   Drive), for the teacher to import in Canvas:
//                                   Settings, Import Course Content, Common
//                                   Cartridge 1.x Package
//   installWeeklyCanvasCartridge()  builds one every Friday afternoon
//   removeWeeklyCanvasCartridge()
//
// WHICH LESSONS. Each course's lessons starting from tomorrow through
// CWC_DAYS_AHEAD days (LessonSchedule, 55), not held. A lesson already in its
// course's newest Canvas gradebook export (58's _lrExportsByCourse_, 00's
// canvasAssignmentFor_) is left out and listed with its due date to set by
// hand: a re-import duplicates what an earlier import made (seen 2026-10-12),
// and a hand-made assignment would be doubled too. One assignment per lesson; a
// lesson in parts is one assignment, as in the full cartridges.
//
// THE ASSIGNMENT. Exactly the full cartridges' (79b, generated by
// tools/cas-ccps/build-canvas-cartridge.js from the same lessons, with the same
// identifiers), the turn-in text entry when
// TURN_IN_CODE_COURSES covers the lesson (71), else the Website URL. Added:
// Canvas's own settings block inside the assignment (<extensions><assignment>,
// which Canvas's Common Cartridge importer reads: lib/cc/importer/standard/
// assignment_converter.rb, read 2026-11-19): the due date, published, the
// submission type and 100 points.
//
// THE DUE DATE. 11:59 p.m. on the school day before the next lesson of the
// course starts (00's lessonDueDay_, which the Student Dashboard shows too):
// a lesson runs until the next one starts (55). A course's last dated lesson
// has none. Canvas reads it as UTC.
//
// Not yet confirmed: one import into a Canvas course (a sandbox course
// first). Canvas's importer is read from its source, not tried here.
//
// FERPA: lesson text and dates only; nothing about students.
// =============================================================================

const CWC_DAYS_AHEAD = 7;
const CWC_DUE_TIME = "23:59";
const CWC_POINTS = 100;
const CWC_TRIGGER_FN = "buildWeeklyCanvasCartridge";

function previewWeeklyCanvasCartridge() {
  return weeklyCanvasCartridge_({ apply: false });
}

function buildWeeklyCanvasCartridge() {
  return weeklyCanvasCartridge_({ apply: true });
}

function installWeeklyCanvasCartridge() {
  if (ScriptApp.getProjectTriggers().some(function (t) { return t.getHandlerFunction() === CWC_TRIGGER_FN; })) {
    Logger.log("[S79] The weekly Canvas cartridge is already installed.");
    return false;
  }
  ScriptApp.newTrigger(CWC_TRIGGER_FN).timeBased().onWeekDay(ScriptApp.WeekDay.FRIDAY).atHour(14).create();
  Logger.log("[S79] Installed: a Canvas cartridge for the next week's lessons every Friday afternoon, in the teacher folder.");
  return true;
}

function removeWeeklyCanvasCartridge() {
  let removed = 0;
  ScriptApp.getProjectTriggers().forEach(function (t) {
    if (t.getHandlerFunction() === CWC_TRIGGER_FN) { ScriptApp.deleteTrigger(t); removed++; }
  });
  Logger.log("[S79] Removed " + removed + " weekly Canvas cartridge trigger(s).");
  return removed;
}

// "yyyy-MM-ddTHH:mm:ss" in UTC for a local day and time in tz (Canvas's
// ims_datetime). The offset is read from tz itself, so daylight time is right.
function cwcUtcStamp_(ymd, hhmm, tz) {
  const p = String(ymd).split("-").map(Number);
  const t = String(hhmm).split(":").map(Number);
  const wanted = Date.UTC(p[0], p[1] - 1, p[2], t[0], t[1]);
  let guess = new Date(wanted);
  for (let i = 0; i < 2; i++) {
    const local = Utilities.formatDate(guess, tz, "yyyy-MM-dd HH:mm").split(/[- :]/).map(Number);
    const shownAsUtc = Date.UTC(local[0], local[1] - 1, local[2], local[3], local[4]);
    guess = new Date(guess.getTime() + (wanted - shownAsUtc));
  }
  return ymd_(guess, "UTC") + "T" + Utilities.formatDate(guess, "UTC", "HH:mm:ss");
}

function _cwcEsc_(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

// The assignment.xml with Canvas's settings block added before its end.
function cwcAssignmentXml_(lesson, turnIn, dueUtc) {
  const base = turnIn ? lesson.text : lesson.url;
  const settings = [
    "  <extensions>",
    "    <assignment identifier=\"" + lesson.assignmentId + "_canvas\" xmlns=\"http://canvas.instructure.com/xsd/cccv1p0\">",
    "      <title>" + _cwcEsc_(lesson.title) + "</title>",
    dueUtc ? "      <due_at>" + dueUtc + "</due_at>" : "",
    "      <workflow_state>published</workflow_state>",
    "      <points_possible>" + CWC_POINTS + "</points_possible>",
    "      <grading_type>points</grading_type>",
    "      <submission_types>" + (turnIn ? "online_text_entry" : "online_url") + "</submission_types>",
    "    </assignment>",
    "  </extensions>",
  ].filter(Boolean).join("\n") + "\n";
  return base.replace(/<\/assignment>\s*$/, settings + "</assignment>\n");
}

// The manifest for one course's chosen lessons, as the full cartridges'
// (build-canvas-cartridge.js manifestXml), with only these modules.
function cwcManifestXml_(course, lessons) {
  const ids = CANVAS_CARTRIDGE_COURSES[course];
  return [
    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
    "<manifest identifier=\"" + ids.manifest + "\" xmlns=\"http://www.imsglobal.org/xsd/imsccv1p3/imscp_v1p1\" " +
      "xmlns:lom=\"http://ltsc.ieee.org/xsd/imsccv1p3/LOM/resource\" xmlns:lomimscc=\"http://ltsc.ieee.org/xsd/imsccv1p3/LOM/manifest\" " +
      "xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" " +
      "xsi:schemaLocation=\"http://www.imsglobal.org/xsd/imsccv1p3/imscp_v1p1 http://www.imsglobal.org/profile/cc/ccv1p3/ccv1p3_imscp_v1p2_v1p0.xsd\">",
    "  <metadata>",
    "    <schema>IMS Common Cartridge</schema>",
    "    <schemaversion>1.3.0</schemaversion>",
    "    <lomimscc:lom>",
    "      <lomimscc:general>",
    "        <lomimscc:title><lomimscc:string>" + _cwcEsc_(ids.title) + "</lomimscc:string></lomimscc:title>",
    "      </lomimscc:general>",
    "    </lomimscc:lom>",
    "  </metadata>",
    "  <organizations>",
    "    <organization identifier=\"" + ids.org + "\" structure=\"rooted-hierarchy\">",
    "      <item identifier=\"LearningModules\">",
  ].concat(lessons.map(function (l) {
    return "        <item identifier=\"" + l.data.moduleId + "\">\n          <title>" + _cwcEsc_(l.data.title) + "</title>\n" +
      "          <item identifier=\"" + l.data.itemId + "\" identifierref=\"" + l.data.assignmentId + "\">\n" +
      "            <title>" + _cwcEsc_(l.data.title) + "</title>\n          </item>\n        </item>";
  })).concat([
    "      </item>",
    "    </organization>",
    "  </organizations>",
    "  <resources>",
  ]).concat(lessons.map(function (l) {
    return "    <resource identifier=\"" + l.data.assignmentId + "\" type=\"assignment_xmlv1p0\">\n" +
      "      <file href=\"" + l.data.assignmentId + "/assignment.xml\"/>\n    </resource>";
  })).concat(["  </resources>", "</manifest>", ""]).join("\n");
}

// opts: { apply, now? }. Returns { apply, from, to, courses: { course: {
// lessons: [{ key, title, start, due, status, canvasTitle? }], file? } },
// message }. status: IN (in the cartridge), ON_CANVAS (already in the
// export: its due date to set by hand), HELD, NO_DATA (not in 79b).
function weeklyCanvasCartridge_(opts) {
  opts = opts || {};
  const cfg = getConfig_();
  const tz = Session.getScriptTimeZone();
  const now = opts.now || new Date();
  const ymd = function (d) { return ymd_(d, tz); };
  const from = ymd(new Date(now.getTime() + 86400000));
  const to = ymd(new Date(now.getTime() + CWC_DAYS_AHEAD * 86400000));
  const out = { apply: opts.apply === true, from: from, to: to, courses: {}, message: "" };
  const all = _lsRows_();
  let exports = {};
  try { exports = _lrExportsByCourse_(_criFindExports_(cfg)); } catch (e) {
    Logger.log("[S79] Canvas exports not read (" + e.message + "): every lesson goes in the cartridge.");
  }
  const raw = _turnInSwitchRaw_();
  const lines = [];
  Object.keys(all).forEach(function (course) {
    const rows = all[course] || [];
    const picked = rows.filter(function (r) { return r.start >= from && r.start <= to; });
    if (!picked.length) return;
    const c = out.courses[course] = { lessons: [] };
    const inCartridge = [];
    picked.forEach(function (r) {
      const data = CANVAS_CARTRIDGE_LESSONS[r.key];
      const due = lessonDueDay_(rows, r);
      const l = { key: r.key, title: data ? data.title : r.key, start: r.start, due: due, status: "IN" };
      c.lessons.push(l);
      if (r.hold) { l.status = "HELD"; return; }
      if (!data) { l.status = "NO_DATA"; return; }
      const found = exports[course] ? canvasAssignmentFor_(exports[course].titles, data.title) : "";
      if (found) { l.status = "ON_CANVAS"; l.canvasTitle = found; return; }
      l.turnIn = turnInSwitchCovers_(course, lessonConfigId_(r.key), raw);
      inCartridge.push({ lesson: l, data: data });
    });
    c.lessons.forEach(function (l) {
      const dueText = l.due ? "due " + l.due + " 11:59 PM" : "no due date (the course's last dated lesson)";
      lines.push("[S79] " + course + " " + l.key + " starts " + l.start + ", " + dueText + ": " +
        ({ IN: "in the cartridge", ON_CANVAS: "already on Canvas as \"" + l.canvasTitle + "\" (set its due date there by hand)",
          HELD: "held in LessonSchedule; left out", NO_DATA: "not in the cartridge data (no approved assignment); left out" })[l.status]);
    });
    if (!out.apply || !inCartridge.length) return;
    const blobs = [Utilities.newBlob(cwcManifestXml_(course, inCartridge), "application/xml", "imsmanifest.xml")];
    inCartridge.forEach(function (x) {
      const dueUtc = x.lesson.due ? cwcUtcStamp_(x.lesson.due, CWC_DUE_TIME, tz) : "";
      blobs.push(Utilities.newBlob(cwcAssignmentXml_(x.data, x.lesson.turnIn, dueUtc), "application/xml",
        x.data.assignmentId + "/assignment.xml"));
    });
    const name = "Canvas " + course + " week of " + from + ".imscc";
    const folder = cfg.teacherFolderId ? DriveApp.getFolderById(cfg.teacherFolderId) : DriveApp.getRootFolder();
    folder.createFile(Utilities.zip(blobs, name));
    c.file = name;
    lines.push("[S79] Wrote " + name + " (" + inCartridge.length + " assignment(s)). In Canvas: Settings, Import Course " +
      "Content, Common Cartridge 1.x Package, this file, All content.");
  });
  const counted = Object.keys(out.courses).reduce(function (n, k) {
    return n + out.courses[k].lessons.filter(function (l) { return l.status === "IN"; }).length;
  }, 0);
  out.message = counted ? counted + " lesson(s) from " + from + " to " + to + (out.apply ? " in this week's cartridge(s)." : " would go in a cartridge.")
    : "No lesson from " + from + " to " + to + " needs a cartridge.";
  lines.forEach(function (l) { Logger.log(l); });
  Logger.log("[S79] " + out.message);
  return out;
}
