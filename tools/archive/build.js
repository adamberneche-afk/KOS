#!/usr/bin/env node
'use strict';
/**
 * tools/archive/build.js
 * ======================
 * Writes the archive's indexes from its data, and checks the data against
 * the files. archive/catalog.jsonl (one record per archived file) and
 * archive/quarters.json are the source; everything below is generated and
 * never edited by hand:
 *
 *   archive/INDEX.md            one row per quarter, linking its index
 *   archive/<quarter>/INDEX.md  that quarter's files, grouped by kind
 *   archive/by-system.md        every record, by system, across quarters
 *   archive/by-pr.md            #N -> every file and log entry citing it
 *   archive/entries.jsonl       one record per entry of an archived log
 *
 * The check fails when a file under archive/<quarter>/ has no record, a
 * record has no file, a field is missing or malformed, a record sits in
 * a quarter its filed_on date doesn't fall in, or a generated file is
 * stale. See tools/archive/README.md.
 *
 * USAGE
 *   node tools/archive/build.js           # rewrite the generated files
 *   node tools/archive/build.js --check   # exit 1 on a problem or a stale file
 *
 * Node built-ins only.
 */

const fs = require('fs');
const path = require('path');
const lib = require('./lib');

function validate(catalog, quarters, root) {
  const errors = [];
  const ids = new Set();
  const qids = quarters.map((q) => q.id);
  catalog.forEach((r, i) => {
    const where = 'catalog.jsonl line ' + (i + 1) + (r.id ? ' (' + r.id + ')' : '');
    lib.REQUIRED.forEach((f) => { if (!r[f]) errors.push(where + ': missing ' + f); });
    if (!r.id) return;
    if (ids.has(r.id)) errors.push(where + ': duplicate id');
    ids.add(r.id);
    if (!qids.includes(r.quarter)) errors.push(where + ': unknown quarter ' + r.quarter);
    if (r.id !== r.quarter + '/' + r.original_path) errors.push(where + ': id must be <quarter>/<original_path>');
    if (lib.isFolder(r) !== r.original_path.endsWith('/')) errors.push(where + ': a folder record ends both id and original_path in /');
    if (!lib.KINDS.includes(r.kind)) errors.push(where + ': kind must be one of ' + lib.KINDS.join(', '));
    ['date', 'filed_on'].forEach((f) => {
      if (r[f] != null && !lib.DATE_RE.test(r[f])) errors.push(where + ': ' + f + ' must be YYYY-MM-DD or YYYY-MM');
    });
    if (r.filed_on && !lib.quartersFor(r.filed_on, quarters).includes(r.quarter)) {
      errors.push(where + ': filed_on ' + r.filed_on + ' is not in ' + r.quarter);
    }
    if (!fs.existsSync(path.join(root || lib.REPO_ROOT, lib.filePath(r)))) errors.push(where + ': no such file');
    if (r.kind === 'history' && !r.continues_in) errors.push(where + ': a history record needs continues_in');
  });
  lib.archivedFiles(quarters, root).forEach((f) => {
    if (!lib.coveringRecord(f, catalog)) errors.push('archive/' + f + ': no catalog record (add one to archive/catalog.jsonl)');
  });
  return errors;
}

function entriesOf(catalog, root) {
  const out = [];
  catalog.filter((r) => r.kind === 'history').forEach((r) => {
    lib.parseEntries(lib.read(lib.filePath(r), root)).forEach((e) => {
      out.push({
        id: r.id + '#' + e.anchor, file: r.id, quarter: r.quarter, system: r.system,
        title: e.title, date: e.date, near: e.near, line: e.line, lines: e.lines, prs: lib.prRefs(e.body),
      });
    });
  });
  return out;
}

const link = (from, rec) => '[`' + rec.original_path + '`](' + path.posix.relative(from, rec.id) + ')';
const planCell = (p) => (p ? '`' + p.replace(' (live)', '') + '`' + (p.includes('(live)') ? ' (live)' : '') : '—');
const when = (r) => r.date || (r.filed_on ? '~' + r.filed_on : 'undated');

function topIndex(catalog, quarters, entries) {
  const L = ['# Archive index', '',
    '<!-- Generated by tools/archive/build.js from archive/catalog.jsonl and',
    '     archive/quarters.json; edit those, then run it. -->', '',
    'Superseded docs and the history logs\' older entries, kept word for word',
    'and filed by **school quarter**: the 2025-26 year, summer 2026, then',
    '2026-27\'s marking periods (CCPS calendar; the dates are in',
    '[`quarters.json`](quarters.json)). Inside a quarter a file keeps its old',
    'path: `meta/HANDOFF_2026-10-22.md` is',
    '`archive/2026-27-Q1/meta/HANDOFF_2026-10-22.md`. Git history follows each',
    'file across the moves (`git log --follow`).', '',
    '**Find something:** `node tools/archive/search.js` filters the catalog',
    '(quarter, kind, system, dates, a `#N` it cites) and then searches the',
    'text of what matched, a history log entry by entry. Examples are in',
    '[`tools/archive/README.md`](../tools/archive/README.md). Two views cut',
    'across quarters: [by system](by-system.md) and [by `#N`](by-pr.md).', '',
    '**Which quarter:** a document goes by the date it was written; one with no',
    'date by the date it was replaced or retired, and its record says so. A',
    'history log\'s entries are indexed one by one (`entries.jsonl`), each by',
    'its heading date, an undated one by where it stood. The live logs hold',
    'the current plan of record\'s era; when the plan rolls over, the older',
    'entries move here.', '',
    '**Out of everyday search:** the root `.ignore` hides `archive/` from',
    'ripgrep (Claude Code\'s Grep). Git, CI, `release-check` and',
    '`student-data-scan` still read every file.', '',
    '**A record, not a guide:** each file was true when written. Links inside',
    'it are relative to its old folder; the code it names may have changed;',
    'where it disagrees with a live doc or the code, they win. The agent notes',
    'from the archived handoffs are live in',
    '[`meta/AGENT_NOTES.md`](../meta/AGENT_NOTES.md).', '',
    '| Quarter | Dates | Files | Log entries | PRs | Plan of record | What it was |',
    '|---|---|---|---|---|---|---|'];
  quarters.forEach((q) => {
    const n = catalog.filter((r) => r.quarter === q.id).length;
    if (!n) return;
    const e = entries.filter((x) => x.quarter === q.id).length;
    const dates = (q.start || '…') + ' to ' + (q.end || '…');
    L.push('| [' + q.title + '](' + q.id + '/INDEX.md) | ' + dates + ' | ' + n + ' | ' + (e || '—') + ' | ' +
      (q.prs || '—') + ' | ' + planCell(q.plan) + ' | ' + q.summary + ' |');
  });
  L.push('', '**Adding to it:** `node tools/archive/file.js <path> --summary "…"` files a',
    'doc or a folder (quarter from its date, `git mv`, links and path mentions',
    'repointed, record added, indexes rebuilt); review the files it lists.',
    'When a plan of record is replaced, `node tools/archive/file.js',
    '--rollover-logs --before <the new plan\'s start>` moves the history logs\'',
    'older entries to their quarters. CI runs `node tools/archive/build.js --check`.', '');
  return L.join('\n');
}

function quarterIndex(q, catalog, entries) {
  const recs = catalog.filter((r) => r.quarter === q.id);
  const from = q.id;
  const L = ['# Archive: ' + q.title, '',
    '<!-- Generated by tools/archive/build.js; edit archive/catalog.jsonl. -->', '',
    (q.start || '…') + ' to ' + (q.end || '…') + '. PRs: ' + (q.prs || '—') + '. Plan of record: ' + (q.plan || '—') + '.', '',
    q.summary, '',
    'One line per file: its date, its old path (the link opens it here), what',
    'it is. `~` marks the date a file was filed by when it has none of its own.',
    'How files are filed and searched: the [archive index](../INDEX.md).', ''];
  lib.KINDS.forEach((k) => {
    const rows = recs.filter((r) => r.kind === k).sort((a, b) => (when(a) + a.id).localeCompare(when(b) + b.id));
    if (!rows.length) return;
    L.push('## ' + lib.KIND_TITLES[k], '');
    rows.forEach((r) => {
      let line = '- ' + when(r) + ' · ' + link(from, r) + ' — ' + r.summary;
      if (r.kind === 'history') {
        const n = entries.filter((e) => e.file === r.id).length;
        line += ' (' + n + ' entries; continues in the live `' + r.continues_in + '`)';
      }
      if (!/^the date in its name$|^the earliest date near its top$|^its own date$/.test(r.filed_by) && r.kind !== 'history') {
        line += ' *(Filed by: ' + r.filed_by + '.)*';
      }
      if (r.superseded_by) line += ' Replaced by `' + r.superseded_by + '`.';
      L.push(line);
    });
    L.push('');
  });
  return L.join('\n');
}

function bySystem(catalog, quarters, entries) {
  const L = ['# Archive by system', '',
    '<!-- Generated by tools/archive/build.js; edit archive/catalog.jsonl. -->', '',
    'Every archived file, grouped by the system its old path is in, oldest',
    'quarter first. History logs show their entry count; search them entry by',
    'entry with `node tools/archive/search.js --system <system>`.', ''];
  const order = quarters.map((q) => q.id);
  [...new Set(catalog.map((r) => r.system))].sort().forEach((s) => {
    L.push('## ' + s + '/', '');
    catalog.filter((r) => r.system === s)
      .sort((a, b) => order.indexOf(a.quarter) - order.indexOf(b.quarter) || when(a).localeCompare(when(b)))
      .forEach((r) => {
        const n = r.kind === 'history' ? ' (' + entries.filter((e) => e.file === r.id).length + ' entries)' : '';
        L.push('- ' + r.quarter + ' · ' + when(r) + ' · [`' + r.original_path + '`](' + r.id + ')' + n + ' — ' + r.summary);
      });
    L.push('');
  });
  return L.join('\n');
}

function byPr(catalog, entries, root) {
  const refs = {};
  const add = (n, label) => { (refs[n] = refs[n] || []).push(label); };
  catalog.filter((r) => r.kind !== 'history' && !lib.isFolder(r) && /\.(md|txt|js|gs|html|json)$/.test(r.id)).forEach((r) => {
    lib.prRefs(lib.read(lib.filePath(r), root)).forEach((n) => add(n, '[`' + r.id + '`](' + r.id + ')'));
  });
  entries.forEach((e) => e.prs.forEach((n) => add(n, '[' + e.file.split('/').slice(1).join('/') + ' · ' +
    (e.date || 'undated') + '](' + e.file + '#' + e.id.split('#')[1] + ')')));
  const L = ['# Archive by #N', '',
    '<!-- Generated by tools/archive/build.js from the archived files. -->', '',
    'Every `#N` the archive cites (two to four digits), with the files and log',
    'entries that cite it. Mostly PR numbers; the RTP\'s decision numbers share',
    'the form. `node tools/archive/search.js --pr N` does the same with the',
    'matching lines.', ''];
  Object.keys(refs).map(Number).sort((a, b) => a - b).forEach((n) => {
    L.push('- **#' + n + '**: ' + refs[n].join(', '));
  });
  L.push('');
  return L.join('\n');
}

function outputs(root) {
  const quarters = lib.loadQuarters(root);
  const catalog = lib.loadCatalog(root);
  const entries = entriesOf(catalog, root);
  const out = {};
  out['archive/INDEX.md'] = topIndex(catalog, quarters, entries);
  quarters.forEach((q) => {
    if (catalog.some((r) => r.quarter === q.id)) out['archive/' + q.id + '/INDEX.md'] = quarterIndex(q, catalog, entries);
  });
  out['archive/by-system.md'] = bySystem(catalog, quarters, entries);
  out['archive/by-pr.md'] = byPr(catalog, entries, root);
  out['archive/entries.jsonl'] = entries.map((e) => JSON.stringify(e)).join('\n') + '\n';
  return { out, errors: validate(catalog, quarters, root) };
}

function main(argv, root) {
  const check = argv.includes('--check');
  const base = root || lib.REPO_ROOT;
  let res;
  try { res = outputs(root); } catch (e) { console.error('archive: ' + e.message); return 1; }
  const { out, errors } = res;
  const stale = [];
  Object.entries(out).forEach(([rel, text]) => {
    const abs = path.join(base, rel);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (cur === text) return;
    if (check) stale.push(rel);
    else fs.writeFileSync(abs, text);
  });
  errors.forEach((e) => console.error('archive: ' + e));
  if (check) {
    stale.forEach((s) => console.error('archive: stale ' + s + ' (run node tools/archive/build.js)'));
    if (errors.length || stale.length) return 1;
    console.log('archive: catalog and indexes current (' + Object.keys(out).length + ' generated files).');
    return 0;
  }
  console.log('archive: wrote the indexes' + (errors.length ? '; ' + errors.length + ' problem(s) above' : '') + '.');
  return errors.length ? 1 : 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { main, outputs, validate, entriesOf };
