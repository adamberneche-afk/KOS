'use strict';
// Regenerates cas-ccps/scripts/13c_StudentDashboardLessons.js: the little
// the Student Dashboard needs to know about every lesson (F16, approved
// 2026-11-14), so its project never loads 55b_LessonAssignmentData.js
// (about 2 MB):
//   DASH_LESSON_ORDER  each course's teaching order (a copy of 55b's
//                      LESSON_ORDER): a card's place in "Assigned order" and
//                      its lesson number chip (L05; 8177's names have none).
//   DASH_LESSON_INFO   per lesson key: its number in the course, the
//                      assignment's short title (the first line of its
//                      task, "Assignment: ..." without the label), every
//                      competency it names with the student's "I can" words
//                      from STUDENT_CRITERIA.json (iCan: the measured
//                      milestones first, primary first, m of them, at most
//                      three, then the rest), and for a lesson in parts each
//                      part's one line on what the student does (its
//                      objective). The cards show the first m; the
//                      Competencies tab reads them all (F17: the student's
//                      words and where each competency is practiced).
// Lesson definitions only, never student data.
//
// Usage: node tools/cas-ccps/build-dashboard-lessons.js [--check]
//   --check: exit 1 if the file would change, without writing it.
// tests/cas-ccps/student-dashboard-navigation.test.js fails when the file is
// out of date with 55b or STUDENT_CRITERIA.json.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const REPO_ROOT = path.join(__dirname, '..', '..');
const LESSONS_PATH = path.join(REPO_ROOT, 'cas-ccps', 'scripts', '55b_LessonAssignmentData.js');
const CRITERIA_PATH = path.join(REPO_ROOT, 'cas-ccps', 'curriculum', 'lessons', 'STUDENT_CRITERIA.json');
const TARGET_PATH = path.join(REPO_ROOT, 'cas-ccps', 'scripts', '13c_StudentDashboardLessons.js');
const MAX_MILESTONES = 3;

function readLessons(source) {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(source + '\nthis.A = LESSON_ASSIGNMENTS; this.O = LESSON_ORDER; this.P = LESSON_PARTS;', ctx);
  return { assignments: ctx.A, order: ctx.O, parts: ctx.P };
}

// "Assignment: The Seven Eras of Marketing (Timeline Analysis)" -> the title.
function taskTitle(promptText) {
  const first = String(promptText || '').split('\n')[0].trim();
  return first.replace(/^(Assignment|Project|Discussion|Extra Credit|Activity)\s*:\s*/i, '').trim();
}

function build(lessonSource, criteriaJson) {
  const { assignments, order, parts } = readLessons(lessonSource);
  const criteria = JSON.parse(criteriaJson);
  const outOrder = {};
  const info = {};
  Object.keys(order).sort().forEach((code) => {
    outOrder[code] = order[code].slice();
    order[code].forEach((key, i) => {
      const a = assignments[key];
      if (!a) return;
      const words = criteria[key] || {};
      const iCan = [];
      (a.milestoneCompetencyIds || []).forEach((id) => {
        id = String(id || '').trim();
        if (!id || iCan.length >= MAX_MILESTONES || iCan.some((m) => m.id === id)) return;
        iCan.push({ id, text: String(words[id] || '').trim() });
      });
      const m = iCan.length;
      Object.keys(words).forEach((id) => {
        if (!iCan.some((x) => x.id === id)) iCan.push({ id, text: String(words[id] || '').trim() });
      });
      const entry = { n: i + 1, task: taskTitle(a.promptText), m, iCan };
      const list = parts[key];
      if (list && list.length) {
        entry.parts = list.map((p) => String(p.objective || '').trim());
      }
      info[key] = entry;
    });
  });
  return { order: outOrder, info };
}

function render(data) {
  return [
    '// =============================================================================',
    '// FILE: 13c_StudentDashboardLessons.js',
    '// BOUND TO: Student Dashboard (cas-ccps:student-dashboard)',
    '// PURPOSE: Each course\'s teaching order and each lesson\'s card text, for the Student Dashboard.',
    '// GENERATED by tools/cas-ccps/build-dashboard-lessons.js from',
    '// 55b_LessonAssignmentData.js and curriculum/lessons/STUDENT_CRITERIA.json.',
    '// Never hand-edit: rebuild after the lessons change.',
    '// Each course\'s teaching order and, per lesson, its number, short title,',
    '// its competencies in the student\'s words (the first m are the measured',
    '// milestones) and its parts\' one-line tasks (13\'s cards, F16, and the',
    '// Competencies tab, F17): lesson definitions only, no student data.',
    '// =============================================================================',
    '',
    'const DASH_LESSON_ORDER = ' + JSON.stringify(data.order) + ';',
    '',
    'const DASH_LESSON_INFO = {',
    Object.keys(data.info).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(data.info[k])).join(',\n'),
    '};',
    '',
  ].join('\n');
}

function expected() {
  return render(build(fs.readFileSync(LESSONS_PATH, 'utf8'), fs.readFileSync(CRITERIA_PATH, 'utf8')));
}

function main() {
  const next = expected();
  const current = fs.existsSync(TARGET_PATH) ? fs.readFileSync(TARGET_PATH, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('13c_StudentDashboardLessons.js is out of date. Run: node tools/cas-ccps/build-dashboard-lessons.js');
      process.exit(1);
    }
    console.log('13c_StudentDashboardLessons.js matches the lesson data.');
    return;
  }
  if (current === next) { console.log('No change.'); return; }
  fs.writeFileSync(TARGET_PATH, next);
  console.log('Wrote ' + path.relative(REPO_ROOT, TARGET_PATH));
}

if (require.main === module) main();
module.exports = { build, render, expected, taskTitle, TARGET_PATH };
