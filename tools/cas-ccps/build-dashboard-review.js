'use strict';
// Regenerates cas-ccps/scripts/13d_StudentDashboardReview.js: the Student
// Dashboard's Competencies tab "Review" panel (F17, SDV-N8, approved
// 2026-11-14), per lesson:
//   recap  { competencyId: the lesson plan's own one-line note on what the
//          competency means in that lesson }, from the parenthetical on
//          its line in the plan's competency alignment list
//          ("**039:** Explain marketing ... (How marketing changed from the
//          Trade Era to the Collaboration Era).")
//   terms  the lesson's key terms (55b's vocabulary), when it has any
//   watch  the lesson's videos with a link today (curriculum/lessons/
//          VIDEO_LINKS.json): [{ title, url }], https only
// Only lessons in a course's teaching order; nothing for a lesson with
// none of these. Lesson definitions only, never student data, and never
// the plans' Drive source lines. The 2 MB 55b is read here, at build time,
// never by the Student Dashboard.
//
// Usage: node tools/cas-ccps/build-dashboard-review.js [--check]
//   --check: exit 1 if the file would change, without writing it.
// tests/cas-ccps/student-dashboard-competencies.test.js fails when the file
// is out of date.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const REPO_ROOT = path.join(__dirname, '..', '..');
const CUR = path.join(REPO_ROOT, 'cas-ccps', 'curriculum');
const LESSONS_PATH = path.join(REPO_ROOT, 'cas-ccps', 'scripts', '55b_LessonAssignmentData.js');
const VIDEOS_PATH = path.join(CUR, 'lessons', 'VIDEO_LINKS.json');
const TARGET_PATH = path.join(REPO_ROOT, 'cas-ccps', 'scripts', '13d_StudentDashboardReview.js');
const RECAP_MAX = 240;

function readLessons(source) {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(source + '\nthis.A = LESSON_ASSIGNMENTS; this.O = LESSON_ORDER;', ctx);
  return { assignments: ctx.A, order: ctx.O };
}

// { "8175-39": "How marketing changed ..." } from a plan's alignment list.
function recapsFromPlan(md, code) {
  const out = {};
  String(md || '').split('\n').forEach((line) => {
    const m = /^\s*-\s*\*\*(?:Competency\s+)?0*(\d+):\*\*\s*(.*)$/.exec(line);
    if (!m) return;
    const rest = m[2].trim().replace(/\.\s*$/, '');
    if (!rest.endsWith(')')) return;
    // The last balanced parenthetical at the end of the line.
    let depth = 0;
    let start = -1;
    for (let i = rest.length - 1; i >= 0; i--) {
      if (rest[i] === ')') depth++;
      else if (rest[i] === '(') { depth--; if (depth === 0) { start = i; break; } }
    }
    if (start <= 0) return;
    let note = rest.slice(start + 1, -1).replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();
    if (!note) return;
    if (note.length > RECAP_MAX) note = note.slice(0, RECAP_MAX - 1).replace(/\s+\S*$/, '') + '…';
    out[code + '-' + Number(m[1])] = note.charAt(0).toUpperCase() + note.slice(1);
  });
  return out;
}

function build(lessonSource, readPlan, videosJson) {
  const { assignments, order } = readLessons(lessonSource);
  const videos = JSON.parse(videosJson);
  const out = {};
  Object.keys(order).sort().forEach((code) => {
    order[code].forEach((key) => {
      const a = assignments[key];
      if (!a) return;
      const entry = {};
      const recap = a.source ? recapsFromPlan(readPlan(a.source), code) : {};
      if (Object.keys(recap).length) entry.recap = recap;
      const terms = String(a.vocabulary || '').replace(/\s+/g, ' ').trim();
      if (terms) entry.terms = terms;
      const watch = (videos[key] || []).filter((v) => v && /^https:\/\//.test(String(v.url || '')))
        .map((v) => ({ title: String(v.title || 'Video').trim(), url: String(v.url).trim() }));
      if (watch.length) entry.watch = watch;
      if (Object.keys(entry).length) out[key] = entry;
    });
  });
  return out;
}

function render(data) {
  return [
    '// =============================================================================',
    '// FILE: 13d_StudentDashboardReview.js',
    '// BOUND TO: Student Dashboard (cas-ccps:student-dashboard)',
    '// GENERATED by tools/cas-ccps/build-dashboard-review.js from the lesson',
    '// plans (curriculum/lessons), 55b\'s vocabulary and VIDEO_LINKS.json.',
    '// Never hand-edit: rebuild after the lessons change.',
    '// The Competencies tab\'s Review panel (F17): each lesson\'s one-line recap',
    '// per competency, key terms and linked videos. No student data.',
    '// =============================================================================',
    '',
    'const DASH_REVIEW = {',
    Object.keys(data).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(data[k])).join(',\n'),
    '};',
    '',
  ].join('\n');
}

function expected() {
  const readPlan = (rel) => {
    const p = path.join(CUR, rel);
    return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  };
  return render(build(fs.readFileSync(LESSONS_PATH, 'utf8'), readPlan, fs.readFileSync(VIDEOS_PATH, 'utf8')));
}

function main() {
  const next = expected();
  const current = fs.existsSync(TARGET_PATH) ? fs.readFileSync(TARGET_PATH, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('13d_StudentDashboardReview.js is out of date. Run: node tools/cas-ccps/build-dashboard-review.js');
      process.exit(1);
    }
    console.log('13d_StudentDashboardReview.js matches the lesson plans.');
    return;
  }
  if (current === next) { console.log('No change.'); return; }
  fs.writeFileSync(TARGET_PATH, next);
  console.log('Wrote ' + path.relative(REPO_ROOT, TARGET_PATH));
}

if (require.main === module) main();
module.exports = { build, render, expected, recapsFromPlan, TARGET_PATH };
