'use strict';
// Writes cas-ccps/docs/SCRIPT_INDEX.md: every file in cas-ccps/scripts/, the
// Apps Script projects it is pushed to, whether it is generated, and its
// one-line purpose (structure audit 4.7, 2026-11-21). Everything is read from
// the files and tools/gas-lint/project-map.json, so the index can't drift:
// `--check` fails when the committed index differs from what this would write.
//
//   node tools/cas-ccps/build-script-index.js           rewrite the index
//   node tools/cas-ccps/build-script-index.js --check   exit 1 if it is stale
//   --out <path>                                        write or check another path
//
// The check also fails, whatever the index says, when:
//   - a script has no `PURPOSE:` line in its first HEADER_LINES lines;
//   - a generated script (its header says "GENERATED by tools/...") is named
//     other than `*Data.js`, unless it is one of GRANDFATHERED (named before
//     the rule; not renamed, since a rename touches every project's push);
//   - a `*Data.js` script is not generated.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SCRIPTS = path.join(ROOT, 'cas-ccps', 'scripts');
const DEFAULT_OUT = path.join(ROOT, 'cas-ccps', 'docs', 'SCRIPT_INDEX.md');
const HEADER_LINES = 40;
const MAX_PURPOSE = 200; // characters; a longer first sentence is cut at a word, with " …"
const GRANDFATHERED = new Set([
  '13b_StudentDashboardDemoLessons.js',
  '13c_StudentDashboardLessons.js',
  '13d_StudentDashboardReview.js',
  '39c_ZeroShotAnswers.js',
  '61_FamilyMailPrompt.js',
]);

// The PURPOSE line's first sentence, followed over continuation lines.
// Accepts `PURPOSE:` and `PURPOSE (a note):`.
function purposeOf(text) {
  const lines = text.split('\n').slice(0, HEADER_LINES);
  const i = lines.findIndex((l) => /^\s*(\/\/|\*)\s*PURPOSE(\s*\([^)]*\))?:/.test(l));
  if (i < 0) return null;
  const strip = (l) => l.replace(/^\s*(\/\/|\*)\s?/, '');
  let out = strip(lines[i]).replace(/^\s*PURPOSE(\s*\([^)]*\))?:\s*/, '');
  for (let k = i + 1; k < lines.length && !/[.!?]["')]?$/.test(out.trim()) && !/[.!?]["')]?\s/.test(out); k++) {
    const next = strip(lines[k]).trim();
    if (!next || /^=+$/.test(next) || /^[A-Z][A-Z ]+:/.test(next)) break;
    out += ' ' + next;
  }
  out = out.trim();
  const end = out.search(/[.!?]["')]?(\s|$)/);
  if (end >= 0) out = out.slice(0, end + 1);
  out = out.replace(/\s+/g, ' ');
  if (out.length > MAX_PURPOSE) out = out.slice(0, out.lastIndexOf(' ', MAX_PURPOSE)).replace(/[,;:—-]\s*$/, '') + ' …';
  return (out.charAt(0).toUpperCase() + out.slice(1)).replace(/[\\|]/g, '\\$&');
}

function generatorOf(text) {
  const m = text.split('\n').slice(0, HEADER_LINES).join('\n')
    .match(/^\s*(?:\/\/|\*)\s*(?:GENERATED|Generated) by (tools\/[\w./-]+\.js)/m);
  return m ? m[1] : null;
}

function projectsByFile() {
  const map = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'gas-lint', 'project-map.json'), 'utf8'));
  const out = {};
  for (const [name, entry] of Object.entries(map)) {
    if (name.startsWith('_') || !name.startsWith('cas-ccps:')) continue;
    for (const f of entry.files || []) (out[path.basename(f)] = out[path.basename(f)] || []).push(name.slice('cas-ccps:'.length));
  }
  return out;
}

function collect() {
  const projects = projectsByFile();
  const files = fs.readdirSync(SCRIPTS).filter((f) => f.endsWith('.js')).sort((a, b) => {
    const na = parseInt(a, 10), nb = parseInt(b, 10);
    return na !== nb ? na - nb : a.localeCompare(b);
  });
  const problems = [];
  const rows = files.map((f) => {
    const text = fs.readFileSync(path.join(SCRIPTS, f), 'utf8');
    const purpose = purposeOf(text);
    const generator = generatorOf(text);
    if (!purpose) problems.push(f + ': no PURPOSE: line in its first ' + HEADER_LINES + ' lines');
    if (generator && !/Data\.js$/.test(f) && !GRANDFATHERED.has(f)) problems.push(f + ': generated, so its name ends in Data.js');
    if (!generator && /Data\.js$/.test(f)) problems.push(f + ': named *Data.js but not generated (no "GENERATED by tools/..." header)');
    return { file: f, projects: projects[f] || [], generator, purpose: purpose || '' };
  });
  return { rows, problems };
}

function render(rows) {
  const generated = rows.filter((r) => r.generator).length;
  const out = [
    '# cas-ccps scripts: the file index',
    '',
    '_Generated by `tools/cas-ccps/build-script-index.js` from each file\'s `PURPOSE:` line and',
    '`tools/gas-lint/project-map.json`. Do not edit: change the file\'s header and run it._',
    '',
    rows.length + ' files, ' + generated + ' of them generated data. The number orders the files and',
    'nothing else: a letter (`34b`, `69c`) is a later file beside its neighbour, generated',
    'or not. A generated file is never edited by hand; its generator is named below.',
    'A new generated file is named `*Data.js` (`79b_CanvasCartridgeData.js`); the five',
    'named before that rule keep their names.',
    '',
    'Projects: `central-ledger`, `teacher-dashboard`, `student-dashboard`, `unified-manual`,',
    '`master-student-template`, `rubric-response-sheet`, `teacher-matrix-sheet`,',
    '`family-sentinel` (the `cas-ccps:` entries in the project map). A file in more than one',
    'shares each project\'s global scope.',
    '',
    '| File | Projects | Generated by | Purpose |',
    '|---|---|---|---|',
  ];
  for (const r of rows) {
    out.push('| `' + r.file + '` | ' + (r.projects.length ? r.projects.join(', ') : 'none') + ' | ' +
      (r.generator ? '`' + r.generator.replace(/^tools\/cas-ccps\//, '') + '`' : '') + ' | ' + r.purpose + ' |');
  }
  return out.join('\n') + '\n';
}

function main(argv) {
  const check = argv.includes('--check');
  const oi = argv.indexOf('--out');
  const outPath = oi >= 0 ? path.resolve(argv[oi + 1]) : DEFAULT_OUT;
  const { rows, problems } = collect();
  if (problems.length) {
    console.error('Script headers break the index rules:\n  ' + problems.join('\n  '));
    return 1;
  }
  const text = render(rows);
  if (check) {
    const cur = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
    if (cur !== text) {
      console.error(path.relative(ROOT, outPath) + ' is stale: run node tools/cas-ccps/build-script-index.js');
      return 1;
    }
    console.log(path.relative(ROOT, outPath) + ' is current (' + rows.length + ' files).');
    return 0;
  }
  fs.writeFileSync(outPath, text);
  console.log('Wrote ' + path.relative(ROOT, outPath) + ' (' + rows.length + ' files).');
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { purposeOf, generatorOf, collect, render };
