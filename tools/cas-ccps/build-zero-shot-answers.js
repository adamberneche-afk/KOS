#!/usr/bin/env node
'use strict';
// Writes cas-ccps/scripts/39c_ZeroShotAnswers.js from the cold answers in
// cas-ccps/curriculum/zero-shot/<lesson key>.txt: one per lesson in 55b,
// each what a general-purpose chatbot gives when a student pastes the whole
// assignment and asks it to do it (written 2026-11-20 from the student-facing
// prompt alone, without the rubric). 39d sends them through Flow 2.
//
//   node tools/cas-ccps/build-zero-shot-answers.js          write 39c
//   node tools/cas-ccps/build-zero-shot-answers.js --check  exit 1 if 39c is stale
//
// Made-up text only: no student wrote any of it.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const DIR = path.join(ROOT, 'cas-ccps', 'curriculum', 'zero-shot');
const OUT = path.join(ROOT, 'cas-ccps', 'scripts', '39c_ZeroShotAnswers.js');

function build() {
  const answers = {};
  fs.readdirSync(DIR).filter((f) => f.endsWith('.txt')).sort().forEach((f) => {
    answers[f.slice(0, -4)] = fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\r\n/g, '\n').trim();
  });
  return '// =============================================================================\n' +
    '// FILE: 39c_ZeroShotAnswers.js\n' +
    '// BOUND TO: Central Ledger spreadsheet (cas-ccps:central-ledger)\n' +
    '// PURPOSE: Each lesson\'s cold answer, written from the student-facing prompt alone, for the zero-shot test (39d).\n' +
    '// GENERATED by tools/cas-ccps/build-zero-shot-answers.js. Do not edit by hand:\n' +
    '// change cas-ccps/curriculum/zero-shot/<lesson key>.txt and run the builder.\n' +
    '// Each lesson\'s cold answer: what a chatbot writes from the student-facing\n' +
    '// prompt alone. Made-up text; 39d sends it through Flow 2.\n' +
    '// =============================================================================\n' +
    'const ZERO_SHOT_ANSWERS = ' + JSON.stringify(answers, null, 2) + ';\n';
}

if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) {
      console.error('39c_ZeroShotAnswers.js is stale: run node tools/cas-ccps/build-zero-shot-answers.js');
      process.exit(1);
    }
    console.log('39c_ZeroShotAnswers.js is current.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Object.keys(JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1))).length + ' lessons)');
  }
}

module.exports = { build, OUT, DIR };
