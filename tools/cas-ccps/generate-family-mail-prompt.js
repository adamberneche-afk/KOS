'use strict';
// Regenerates cas-ccps/scripts/61_FamilyMailPrompt.js FROM its one canonical
// source, cas-ccps/docs/FAMILY_MAIL_TRIAGE_PROMPT.md (meta/FLOW_DOCTRINE.md
// rule 16): everything after the file's first line that is exactly "---".
// Never hand-edit 61_FamilyMailPrompt.js; edit the .md and run this.
// tests/cas-ccps/family-mail-sentinel.test.js fails when the two disagree.
//
// Usage: node tools/cas-ccps/generate-family-mail-prompt.js [--check]
//   --check: exit 1 if the file would change, without writing it.

const fs = require('fs');
const path = require('path');
const { escapeForTemplateLiteral } = require('../lib/escape-template-literal');

const REPO_ROOT = path.join(__dirname, '..', '..');
const SOURCE_PATH = path.join(REPO_ROOT, 'cas-ccps', 'docs', 'FAMILY_MAIL_TRIAGE_PROMPT.md');
const TARGET_PATH = path.join(REPO_ROOT, 'cas-ccps', 'scripts', '61_FamilyMailPrompt.js');

function extractPrompt(markdown) {
  const lines = String(markdown).replace(/\r\n/g, '\n').split('\n');
  const rule = lines.indexOf('---');
  if (rule === -1) throw new Error('FAMILY_MAIL_TRIAGE_PROMPT.md has no "---" line above the prompt.');
  return lines.slice(rule + 1).join('\n').trim();
}

function render(prompt) {
  return [
    '// =============================================================================',
    '// FILE: 61_FamilyMailPrompt.js',
    '// BOUND TO: Family Mail Sentinel spreadsheet (cas-ccps:family-sentinel)',
    '// GENERATED by tools/cas-ccps/generate-family-mail-prompt.js from',
    '// cas-ccps/docs/FAMILY_MAIL_TRIAGE_PROMPT.md. Never hand-edit: edit the .md,',
    '// run the generator, push (meta/FLOW_DOCTRINE.md rule 16).',
    '// =============================================================================',
    '',
    'const FAMILY_MAIL_TRIAGE_PROMPT = `',
    escapeForTemplateLiteral(prompt),
    '`.trim();',
    '',
  ].join('\n');
}

function main() {
  const next = render(extractPrompt(fs.readFileSync(SOURCE_PATH, 'utf8')));
  const current = fs.existsSync(TARGET_PATH) ? fs.readFileSync(TARGET_PATH, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('61_FamilyMailPrompt.js is out of date. Run: node tools/cas-ccps/generate-family-mail-prompt.js');
      process.exit(1);
    }
    console.log('61_FamilyMailPrompt.js matches FAMILY_MAIL_TRIAGE_PROMPT.md.');
    return;
  }
  if (current === next) { console.log('No change.'); return; }
  fs.writeFileSync(TARGET_PATH, next);
  console.log('Wrote ' + path.relative(REPO_ROOT, TARGET_PATH));
}

if (require.main === module) main();

module.exports = { extractPrompt, render, SOURCE_PATH, TARGET_PATH };
