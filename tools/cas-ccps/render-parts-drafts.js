#!/usr/bin/env node
'use strict';
/**
 * The teacher's copy of every lesson in parts: meta/LESSON_PARTS_2026-10.md,
 * one section per lesson in Appendix B's shape (meta/STUDENT_WORK_PLAN_2026-10.md):
 * the tiers table, why, the criteria in a student's words, and what is still
 * open. It reads the approved lessons (lessons/PARTS.json) and any drafts
 * awaiting approval (lessons/PARTS_DRAFTS.json; approving one moves its entry,
 * unchanged, into PARTS.json once `check-parts-drafts.js` passes).
 *
 *   node tools/cas-ccps/render-parts-drafts.js          write the file
 *   node tools/cas-ccps/render-parts-drafts.js --check  exit 1 if it is out of date
 */

const fs = require('fs');
const path = require('path');
const { draftsIn, DRAFTS_FILE } = require('./check-parts-drafts.js');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'meta', 'LESSON_PARTS_2026-10.md');
const PARTS_FILE = path.join(ROOT, 'cas-ccps', 'curriculum', 'lessons', 'PARTS.json');
const RUBRICS = path.join(ROOT, 'cas-ccps', 'data', 'CompetencyRubrics.json');
const DATA_55B = path.join(ROOT, 'cas-ccps', 'scripts', '55b_LessonAssignmentData.js');

const WORK = { doc: 'Doc', form: '**Form**', slides: '**Slides**', sheet: '**Sheet**' };

function lessonNames() {
  const vm = require('vm');
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(DATA_55B, 'utf8').replace(/^const /mg, 'var '), ctx);
  return Object.fromEntries(Object.entries(ctx.LESSON_ASSIGNMENTS).map(([k, a]) => [k, a.unitName]));
}

function render(drafts, across) {
  const text = Object.fromEntries(JSON.parse(fs.readFileSync(RUBRICS, 'utf8')).competency_rubrics
    .map((r) => [r.competency_id, r.competency_text]));
  const names = lessonNames();
  const comp = (id) => id + ' ' + (text[id] || '');
  const keys = Object.keys(drafts).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  const out = [
    '# Lessons in parts (2026-10)',
    '',
    '<!-- Generated by tools/cas-ccps/render-parts-drafts.js from',
    '     cas-ccps/curriculum/lessons/PARTS.json and PARTS_DRAFTS.json; edit the JSON, not this file. -->',
    '',
    'Every lesson split into parts (' + keys.length + '; `meta/STUDENT_WORK_PLAN_2026-10.md`, Phase 3).',
    'Each part is its own assignment and work file; its **primary** unlocks the next part. Every',
    'lesson competency is in some part. The first lesson, 8177 Market Research, is the pattern',
    '(Appendix B, approved 2026-10-27); the other 34 were drafted in it and approved together on',
    '2026-10-28, to be edited as they are taught. Edit a lesson in `PARTS.json`, run',
    '`node tools/cas-ccps/build-lesson-assignments.js`, then this file\'s generator.',
    '',
    'The "Still open" lines are questions the drafts raised, left for when each lesson is taught.',
    '',
    '## Across lessons',
    '',
    ...across.map((a) => '- ' + a),
    '',
    '## Lessons',
    '',
    ...keys.map((k) => '- [' + (names[k] || k) + '](#' + k + ') (' + drafts[k].parts.length + ' parts)'),
    '',
  ];
  keys.forEach((k) => {
    const d = drafts[k];
    out.push('<a id="' + k + '"></a>', '', '## ' + (names[k] || k), '', '`' + k + '` · ' +
      (d.approved ? 'approved ' + d.approved : d.status), '');
    out.push('| Part | Work file | Primary (unlocks the next part) | Secondary | Tertiary |', '|---|---|---|---|---|');
    d.parts.forEach((p, i) => {
      out.push('| ' + (i + 1) + '. ' + p.title + ' | ' + (WORK[p.workFile] || p.workFile) + ' | ' + comp(p.primary) + ' | ' +
        ((p.secondary || []).map(comp).join('; ') || '—') + ' | ' + ((p.tertiary || []).map(comp).join('; ') || '—') + ' |');
    });
    out.push('', '**Why:** ' + (d.why || 'see `meta/STUDENT_WORK_PLAN_2026-10.md`, Appendix B.'), '',
      '**Criteria in a student\'s words:**', '');
    d.parts.forEach((p, i) => {
      out.push('- **Part ' + (i + 1) + '**' + (p.vocabulary && p.vocabulary.length ? ' (terms: ' + p.vocabulary.join(', ') + ')' : ''));
      const tier = (id) => (id === p.primary ? '*(required)* ' : (p.tertiary || []).indexOf(id) !== -1 ? '*(not required)* ' : '');
      [p.primary].concat(p.secondary || [], p.tertiary || []).forEach((id) => {
        out.push('  - ' + tier(id) + p.criteria[id] + ' (' + id + ')');
      });
    });
    if ((d.concerns || []).length) {
      out.push('', '**Still open:**', '');
      d.concerns.forEach((c) => out.push('- ' + c));
    }
    out.push('');
  });
  return out.join('\n');
}

function main() {
  const lessons = Object.assign(draftsIn(PARTS_FILE), draftsIn(DRAFTS_FILE));
  const md = render(lessons, JSON.parse(fs.readFileSync(DRAFTS_FILE, 'utf8'))._across || []);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== md) {
      console.error(path.relative(ROOT, OUT) + ' is out of date. Run: node tools/cas-ccps/render-parts-drafts.js');
      process.exit(1);
    }
    console.log(path.relative(ROOT, OUT) + ' up to date.');
    return;
  }
  fs.writeFileSync(OUT, md);
  console.log('Wrote ' + path.relative(ROOT, OUT) + '.');
}

module.exports = { render };

if (require.main === module) main();
