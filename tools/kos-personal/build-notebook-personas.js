#!/usr/bin/env node
'use strict';
/**
 * Writes the notebook edition of each persona doc into
 * kos-personal/rtp-core-router/notebook-sources/ (RTP notebook plan, Phase 2
 * step 1; notebook-plan/02_PRD.md §5 "Tier B").
 *
 * A notebook retrieves passages, not whole documents, so a persona rule
 * spread over several sections can come back in part, and a passage from
 * the middle of a doc doesn't say whose rule it is. Each edition therefore:
 *   - keeps the doc's title line;
 *   - replaces the preamble before the first `---` rule (the "Gemini Gem
 *     System Prompt" label, version notes and addenda, which are history,
 *     not rules) with the persona's core block from notebook-sources/cores/
 *     <NAME>.md, a short summary of its role, prefix, triggers and hard
 *     rules with section citations;
 *   - puts the persona name in every heading ("## THE_MUSE · 3. THE LOGIC
 *     GATES"), outside code fences only.
 * Everything else is the canonical doc, unchanged. The repo doc stays the
 * source: edit it or the core, then re-run this.
 *
 *   node tools/kos-personal/build-notebook-personas.js          write the editions
 *   node tools/kos-personal/build-notebook-personas.js --check  exit 1 if any is out of date
 */

const fs = require('fs');
const path = require('path');

const ROUTER_DIR = path.join(__dirname, '..', '..', 'kos-personal', 'rtp-core-router');
const OUT_DIR = path.join(ROUTER_DIR, 'notebook-sources');
const CORES_DIR = path.join(OUT_DIR, 'cores');
const PERSONAS = ['ALIGNMENT', 'ARCHITECT', 'AUDITOR', 'CURATOR', 'DEVELOPER', 'MUSE'];

/** The doc's "Persona Name" and "Mandatory Prefix" field values. */
function fields(src) {
  const name = /\*\*Persona Name:\*\*\s*(\S+)/.exec(src);
  const prefix = /\*\*Mandatory Prefix:\*\*\s*`([^`]+)`/.exec(src);
  if (!name || !prefix) throw new Error('no Persona Name / Mandatory Prefix field');
  return { name: name[1], prefix: prefix[1] };
}

function edition(key) {
  const file = 'PERSONA_' + key + '_V5_1.md';
  const src = fs.readFileSync(path.join(ROUTER_DIR, file), 'utf8');
  const core = fs.readFileSync(path.join(CORES_DIR, key + '.md'), 'utf8').trim();
  const { name, prefix } = fields(src);
  if (!core.startsWith('## ' + name + ' · Core\n')) throw new Error(key + ': core must start "## ' + name + ' · Core"');
  if (core.indexOf('`' + prefix + '`') === -1) throw new Error(key + ': core does not quote the Mandatory Prefix ' + prefix);

  const lines = src.split('\n');
  const rule = lines.findIndex((l, i) => i > 0 && /^-{3,}\s*$/.test(l));
  if (!/^# /.test(lines[0]) || rule === -1) throw new Error(key + ': expected a title line and a --- rule after the preamble');

  let fence = false;
  const body = lines.slice(rule).map((l) => {
    if (/^\s*(```|~~~)/.test(l)) fence = !fence;
    if (fence) return l;
    const h = /^(#{2,6})\s+(.*)$/.exec(l);
    if (!h || h[2].startsWith(name + ' ')) return l;
    return h[1] + ' ' + name + ' · ' + h[2];
  });

  const out = [
    lines[0],
    '',
    '_Notebook edition of `' + file + '`, generated by `tools/kos-personal/build-notebook-personas.js`. ' +
      'Every heading names ' + name + ', so any passage can be attributed. Edit the repo doc or its core, not this file._',
    '',
    core,
    '',
    ...body,
  ].join('\n').replace(/\n*$/, '\n');
  return { file, name, text: out };
}

function build() {
  return PERSONAS.map(edition);
}

function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  build().forEach((e) => {
    const p = path.join(OUT_DIR, e.file);
    if (fs.existsSync(p) && fs.readFileSync(p, 'utf8') === e.text) return;
    if (check) stale.push(e.file); else fs.writeFileSync(p, e.text);
  });
  if (check) {
    if (stale.length) {
      console.error('notebook persona editions out of date: ' + stale.join(', '));
      console.error('Run: node tools/kos-personal/build-notebook-personas.js');
      process.exit(1);
    }
    console.log('notebook persona editions up to date.');
  } else {
    console.log('Wrote ' + PERSONAS.length + ' notebook persona edition(s) to ' + path.relative(process.cwd(), OUT_DIR) + '.');
  }
}

if (require.main === module) main();
module.exports = { build, edition, PERSONAS };
